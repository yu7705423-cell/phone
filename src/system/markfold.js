const fold = s => [...s].map(ch => T2S[ch] || ch).join('');

// 开括号之后、冒号或收口之前的那一段。方括号两种都认；圆括号只认整行那种（行首到行尾），
// 正文里夹着的（當然）不碰 —— 虽然换完也认不出，不必去试
const HEAD = /([[【])(\s*)([^\]】:：\n]{1,8}?)(\s*)(?=[:：\]】])/g;
const LINE = /^([(（])(\s*)([^)）:：\n]{1,8}?)(\s*)(?=[:：)）]\s*$)/gm;

/** 把标记名里的繁体换成简体。换完认不出的原样留着 */
export function foldMarks(text) {
  const swap = (all, open, a, head, b) => {
    if (!/[^\x00-\x7f]/.test(head)) return all;
    const s = fold(head);
    return s !== head && HEADS.has(s) ? `${open}${a}${s}${b}` : all;
  };
  return String(text || '').replace(HEAD, swap).replace(LINE, swap);
}
